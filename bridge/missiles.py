"""Ballistic missile strikes by mission groups (Iskander, Scud), through a Lua file run by Olympus.

Olympus's fireAtArea cannot say how many rounds to fire, so the bridge gives the group a DCS FireAtPoint
task itself, with an expend quantity. The group is found by its mission editor name.
"""

from __future__ import annotations

import logging
import uuid
from pathlib import Path

from .olympus import OlympusClient

log = logging.getLogger(__name__)

LUA = """-- Generated by the Red Commander bridge: missile strike. Safe to delete.
local g = Group.getByName("{group}")
if g and g:isExist() then
  local p = coord.LLtoLO({lat:.6f}, {lng:.6f}, 0)
  g:getController():setOnOff(true)  -- the mission may have switched the group's AI off until its own strike
  g:getController():setTask({{ id = "FireAtPoint", params = {{
    x = p.x, y = p.z, radius = 50, expendQty = {rounds}, expendQtyEnabled = true }} }})
  Olympus.executionResults["{key}"] = "fired"
else
  Olympus.executionResults["{key}"] = "no group"
end
"""


def lua_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def build_lua(key: str, group: str, lat: float, lng: float, rounds: int) -> str:
    return LUA.format(key=key, group=lua_string(group), lat=lat, lng=lng, rounds=int(rounds))


def fire(client: OlympusClient, group: str, lat: float, lng: float, rounds: int, work_dir: Path) -> str:
    """Order the group to fire. Returns the key its result is published under (Olympus.executionResults)."""
    key = "redcmd-strike-" + uuid.uuid4().hex[:12]
    work_dir.mkdir(parents=True, exist_ok=True)
    path = work_dir / f"strike-{key}.lua"
    path.write_text(build_lua(key, group, lat, lng, rounds), encoding="utf-8")
    client.execute_file(path)
    return key
